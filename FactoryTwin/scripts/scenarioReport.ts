/**
 * Produces docs/scenario-results.md: baseline vs changed numbers for the three one-click
 * scenarios, computed by headless simulation (same seeds for both sides), plus an optimizer run
 * that justifies the "optimized" preset.
 *
 *   npm run report              (full: optimizer budget 40, 3 seeds x 4 days)
 *   npm run report -- --quick   (smaller budget)
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { describeChanges } from '../src/optimization/params';
import { compare, type Comparison } from '../src/optimization/evaluate';
import { optimize } from '../src/optimization/optimizer';
import { breakdownScenario, growthScenario, OPTIMIZED_PARAMS, optimizedScenario } from '../src/scenarios/presets';
import { defaultScenario, DEFAULT_SEED } from '../src/scenarios/default';

const quick = process.argv.includes('--quick');
const seeds = [DEFAULT_SEED, DEFAULT_SEED + 1, DEFAULT_SEED + 2];

function table(c: Comparison, title: string, a: string, b: string): string {
  const fmt = (m: string, v: number) =>
    /On-time|utilisation/.test(m) ? `${(v * 100).toFixed(1)}%` : Math.abs(v) >= 1000 ? Math.round(v).toLocaleString('en-US') : v.toFixed(1);
  const rows = c.rows.map((r) => {
    const d = r.variant.mean - r.baseline.mean;
    const rel = r.baseline.mean !== 0 ? (d / Math.abs(r.baseline.mean)) * 100 : 0;
    return `| ${r.metric} | ${fmt(r.metric, r.baseline.mean)} ± ${fmt(r.metric, r.baseline.std)} | ${fmt(r.metric, r.variant.mean)} ± ${fmt(r.metric, r.variant.std)} | ${rel >= 0 ? '+' : ''}${rel.toFixed(1)}% |`;
  });
  return [
    `### ${title}`,
    '',
    `| Metric (mean ± std over ${seeds.length} seeds) | ${a} | ${b} | Change |`,
    '|---|---|---|---|',
    ...rows,
    `| Bottleneck (per seed) | ${c.bottlenecks.baseline.join(', ')} | ${c.bottlenecks.variant.join(', ')} | |`,
    '',
  ].join('\n');
}

const t0 = performance.now();
const out: string[] = [
  '# Scenario results',
  '',
  `Generated by \`npm run report\` (headless simulation, seeds ${seeds.join(', ')}). Every number below comes from the simulation event log.`,
  '',
];

console.log('1/4 normal operation (5 days)...');
const normal = compare(defaultScenario(), defaultScenario(), seeds, 5);
out.push(
  '## 1. Normal operation',
  '',
  'The calibrated default plant over 5 days. Baseline and scenario are the same configuration, so this table doubles as a reproducibility check (identical seeds give identical results, zero change).',
  '',
  table(normal, 'Normal operation, 5 days', 'Baseline', 'Normal operation'),
);

console.log('2/4 breakdown (1 and 3 days)...');
const broke1 = compare(defaultScenario(), breakdownScenario(), seeds, 1);
const broke3 = compare(defaultScenario(), breakdownScenario(), seeds, 3);
out.push(
  '## 2. Major equipment breakdown',
  '',
  'Assembly Cell 2 fails at 07:30 on day 1 (main drive replaced: 10 h repair once the technician arrives) and conveyor C2 into packaging fails at 09:00 (90 min). Day 1 shows the hit; three days show the recovery, where the backlog is worked off at the cost of longer lead times.',
  '',
  table(broke1, 'Breakdown vs normal, day 1', 'Normal', 'Breakdown'),
  table(broke3, 'Breakdown vs normal, 3 days (recovery)', 'Normal', 'Breakdown'),
);

console.log('3/4 optimizer on growth demand...');
const opt = optimize(
  growthScenario(),
  { budget: quick ? 16 : 60, seeds: seeds.slice(0, quick ? 2 : 3), days: 4, baseSeed: DEFAULT_SEED },
  (p) => {
    if (p.evaluated % 5 === 0) console.log(`   ${p.evaluated} candidates, best ${Math.round(p.best?.objective.mean ?? 0)}`);
  },
);
// keep the one-click preset equal to the optimizer's #1 result
const best = opt.top[0];
if (best && !quick) {
  const changed: Record<string, number> = {};
  for (const k of Object.keys(best.params)) if (best.params[k] !== opt.baseline.params[k]) changed[k] = best.params[k];
  const body = Object.entries(changed).map(([k, v]) => `  '${k}': ${v},`).join('\n');
  writeFileSync(
    'src/scenarios/optimizedParams.ts',
    `// Generated by \`npm run report\` (scripts/scenarioReport.ts): the optimizer's #1 recommendation\n// for the growth-demand scenario. Do not edit by hand.\nexport const OPTIMIZED_PARAMS: Record<string, number> = {\n${body}\n};\n`,
  );
  for (const k of Object.keys(OPTIMIZED_PARAMS)) delete OPTIMIZED_PARAMS[k];
  Object.assign(OPTIMIZED_PARAMS, changed);
  console.log('preset parameters:', describeChanges(opt.baseline.params, best.params).join('; '));
}

out.push(
  '## 3. Improved throughput after optimization',
  '',
  `Growth demand (+25% orders). The optimizer (hill climbing, ${opt.evaluated} candidates, objective = revenue - operating cost - lateness penalty per day, ${quick ? 2 : 3} seeds x 4 days per candidate) recommends:`,
  '',
  ...opt.top.map(
    (t, i) =>
      `${i + 1}. **+$${Math.round(t.gain).toLocaleString('en-US')}/day** (throughput ${Math.round(t.throughputPerDay.mean)} vs ${Math.round(opt.baseline.throughputPerDay.mean)} units/day): ${t.changes.join('; ')}`,
  ),
  '',
  `The one-click preset applies: ${Object.entries(OPTIMIZED_PARAMS)
    .map(([k, v]) => `\`${k} = ${v}\``)
    .join(', ')}.`,
  '',
);

console.log('4/4 optimized preset vs growth baseline (5 days)...');
const better = compare(growthScenario(), optimizedScenario(), seeds, 5);
out.push(table(better, 'Optimized vs growth baseline, 5 days', 'Growth baseline', 'Optimized'));
out.push(`_Report generated in ${((performance.now() - t0) / 1000).toFixed(0)} s._`, '');

mkdirSync('docs', { recursive: true });
writeFileSync('docs/scenario-results.md', out.join('\n'));
console.log(JSON.stringify(opt.top.map((t) => t.changes)));
console.log('wrote docs/scenario-results.md');
