function cassette(letter: 'A' | 'B' | 'C', denom: string): ComponentInfo {
  return {
    id: `cassette-${letter}` as ComponentId,
    name: `Cassette ${letter} (${denom} notes)`,
    group: 'Safe',
    purpose: `Holds the stack of ${denom} notes that the dispenser draws from. Each cassette carries one denomination so the ATM always knows which note it is picking.`,
    howItWorks: `The cassette is a locked, tamper-evident box with a spring-loaded or motor-driven pusher plate that keeps the stack pressed towards the pick opening at the rear. Sensors detect whether the cassette is seated, whether it is nearly empty or empty, and its configured denomination, commonly through a setting held in the ATM software plus a physical identifier on the cassette. When the controller requests notes, the picker rollers take one note at a time from the face of the stack. Only authorised custodians load cassettes, and the loaded count is recorded so the ATM can reconcile what it has dispensed.`,
    relationships: `Sits in the lower safe and feeds the picker rollers and the transport of the Cash dispenser. Its count is tracked by the Controller PC. Notes that fail checking go to the Reject cassette, never back into this one. The Safe protects it.`,
    inputs: `Notes loaded by authorised custodians during replenishment; pick commands from the dispenser; pusher plate pressure.`,
    outputs: `Single notes presented at the pick position; low and empty level signals; cassette present and locked status.`,
    failures: [
      `Low or empty cassette: the denomination can no longer be dispensed and some amounts become impossible.`,
      `Notes stuck together, curled or damaged, causing mis-picks and double picks.`,
      `Pusher plate or spring fault so the stack does not reach the picker.`,
      `Cassette not seated or not locked, so the ATM reports it as missing.`,
      `Wrong denomination loaded or configured, producing incorrect payouts and reconciliation differences.`,
    ],
    maintenance: [
      `Replenish on schedule using counted, fit notes, under dual control.`,
      `Check cassette configuration matches the denomination actually loaded.`,
      `Remove damaged, taped or very worn notes before loading.`,
      `Inspect the pusher mechanism and cassette latch for wear and dust.`,
      `Reconcile the physical count against the ATM counters at each cash-in.`,
    ],
    genericNote: `Cassette size, how many notes it holds, whether it has a cover, and whether it pulls out of the front or the rear differ by manufacturer. Some dispensers use cassettes that can also take deposited notes (recycling). This simulator uses three dispensing cassettes in a stack: A ($20), B ($50) and C ($100).`,
  };
}

